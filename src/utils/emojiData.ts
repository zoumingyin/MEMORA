/** 按名称/关键词/字符模糊搜索（关键词命中按权重排序） */
export function searchEmojis(query: string): EmojiItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const q1 = q[0] ?? "";
  const hit: Array<{ item: EmojiItem; score: number }> = [];
  for (const category of EMOJI_CATEGORIES) {
    for (const item of category.emojis) {
      if (item.emoji === q) {
        hit.push({ item, score: 0 });
        continue;
      }
      const nameScore = item.name.includes(q) ? 1 : 0;
      let kwScore = 0;
      if (item.keywords.some((k) => k === q)) kwScore = 2;
      else if (item.keywords.some((k) => k.includes(q1) && k.includes(q))) kwScore = 1;
      const score = nameScore + kwScore;
      if (score > 0) hit.push({ item, score });
    }
  }
  return hit.sort((a, b) => a.score - b.score).map((h) => h.item).slice(0, 60);
}

/** 最近使用（localStorage 持久化，最多 MAX_RECENT 个） */
const RECENT_KEY = "bianqian.recentEmojis.v1";
export const MAX_RECENT = 18;

export function loadRecentEmojis(): string[] {
  try {
    const raw = localStorage.getItem(RECENT_KEY);
    const list = raw ? (JSON.parse(raw) as string[]) : [];
    return Array.isArray(list) ? list.filter((e) => typeof e === "string") : [];
  } catch {
    return [];
  }
}

export function pushRecentEmoji(emoji: string): void {
  try {
    const list = loadRecentEmojis().filter((e) => e !== emoji);
    list.unshift(emoji);
    localStorage.setItem(RECENT_KEY, JSON.stringify(list.slice(0, MAX_RECENT)));
  } catch {
    // 存储不可用时静默降级（最近使用仅作增强）
  }
}
